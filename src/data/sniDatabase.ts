export function normalizeSniCityName(name: string): string {
  if (!name) return '';
  return name
    .toUpperCase()
    .trim()
    .replace(/^KABUPATEN\s+/i, 'KAB. ')
    .replace(/^KODYA\s+/i, 'KOTA ')
    .replace(/[^A-Z0-9\s\.]/g, '')
    .replace(/\s+/g, ' ');
}

export function findSniByCityName(cityName: string): SniLovItem | undefined {
  if (!cityName) return undefined;
  const rawClean = cityName.trim().toUpperCase();
  const normalized = normalizeSniCityName(cityName);
  
  // 1. Exact match on citySni
  let match = SNI_DATABASE.find(item => item.citySni.toUpperCase() === rawClean);
  if (match) return match;

  // 2. Normalized match (e.g. KAB. SOLOK vs KABUPATEN SOLOK)
  match = SNI_DATABASE.find(item => normalizeSniCityName(item.citySni) === normalized);
  if (match) return match;

  // 3. Match without prefix (e.g. SOLOK, BANDA ACEH)
  const baseName = normalized.replace(/^(KAB\.\s*|KOTA\s*)/i, '').trim();
  if (baseName.length >= 3) {
    match = SNI_DATABASE.find(item => {
      const itemBase = normalizeSniCityName(item.citySni).replace(/^(KAB\.\s*|KOTA\s*)/i, '').trim();
      return itemBase === baseName;
    });
  }

  return match;
}

export function findSniByCityId(cityId: string): SniLovItem | undefined {
  if (!cityId) return undefined;
  const cleanId = cityId.trim().toUpperCase();
  return SNI_DATABASE.find(item => item.cityId === cleanId);
}

export function findSniByPlantAndCity(plant: string, cityId: string): SniLovItem | undefined {
  if (!plant || !cityId) return undefined;
  const cleanPlant = plant.trim().toUpperCase();
  const cleanCity = cityId.trim().toUpperCase();
  return SNI_DATABASE.find(item => item.plant === cleanPlant && item.cityId === cleanCity);
}

function calculateLevenshtein(a: string, b: string): number {
  const matrix: number[][] = [];
  for (let i = 0; i <= b.length; i++) matrix[i] = [i];
  for (let j = 0; j <= a.length; j++) matrix[0][j] = j;

  for (let i = 1; i <= b.length; i++) {
    for (let j = 1; j <= a.length; j++) {
      if (b.charAt(i - 1) === a.charAt(j - 1)) {
        matrix[i][j] = matrix[i - 1][j - 1];
      } else {
        matrix[i][j] = Math.min(
          matrix[i - 1][j - 1] + 1,
          matrix[i][j - 1] + 1,
          matrix[i - 1][j] + 1
        );
      }
    }
  }
  return matrix[b.length][a.length];
}

function calculateBigramSimilarity(a: string, b: string): number {
  if (a.length < 2 || b.length < 2) return a === b ? 1 : 0;
  const getBigrams = (str: string) => {
    const bigrams = new Set<string>();
    for (let i = 0; i < str.length - 1; i++) {
      bigrams.add(str.substring(i, i + 2));
    }
    return bigrams;
  };

  const bgA = getBigrams(a);
  const bgB = getBigrams(b);
  let intersection = 0;
  bgA.forEach(item => {
    if (bgB.has(item)) intersection++;
  });
  return (2.0 * intersection) / (bgA.size + bgB.size);
}

export function fuzzyMatchSniCityName(cityName: string): {
  sniItem: SniLovItem;
  similarity: number;
  confidence: 'HIGH' | 'MEDIUM' | 'LOW';
  suggestionText: string;
} | null {
  if (!cityName || cityName.trim().length < 3) return null;

  const exact = findSniByCityName(cityName);
  if (exact) {
    return {
      sniItem: exact,
      similarity: 1.0,
      confidence: 'HIGH',
      suggestionText: exact.citySni
    };
  }

  let input = normalizeSniCityName(cityName);
  input = input.replace(/TMR/g, 'TIMUR')
    .replace(/SEL/g, 'SELATAN')
    .replace(/SLT/g, 'SELATAN')
    .replace(/BRT/g, 'BARAT')
    .replace(/UTR/g, 'UTARA')
    .replace(/PST/g, 'PUSAT')
    .replace(/KODYA/g, 'KOTA');

  const baseInput = input.replace(/^(KAB\.\s*|KOTA\s*)/i, '').trim();

  let bestMatch: SniLovItem | null = null;
  let bestScore = 0;

  for (const item of SNI_DATABASE) {
    const itemNorm = normalizeSniCityName(item.citySni);
    const itemBase = itemNorm.replace(/^(KAB\.\s*|KOTA\s*)/i, '').trim();

    const levDist = calculateLevenshtein(input, itemNorm);
    const maxLen = Math.max(input.length, itemNorm.length);
    const levSim = Math.max(0, 1 - (levDist / maxLen));
    const biSim = calculateBigramSimilarity(input, itemNorm);

    const baseLevDist = calculateLevenshtein(baseInput, itemBase);
    const baseMaxLen = Math.max(baseInput.length, itemBase.length);
    const baseLevSim = Math.max(0, 1 - (baseLevDist / baseMaxLen));
    const baseBiSim = calculateBigramSimilarity(baseInput, itemBase);

    const score = Math.max(
      (levSim * 0.4) + (biSim * 0.6),
      (baseLevSim * 0.4) + (baseBiSim * 0.6)
    );

    if (score > bestScore) {
      bestScore = score;
      bestMatch = item;
    }
  }

  if (bestMatch && bestScore >= 0.55) {
    const confidence: 'HIGH' | 'MEDIUM' | 'LOW' = 
      bestScore >= 0.78 ? 'HIGH' : bestScore >= 0.65 ? 'MEDIUM' : 'LOW';

    return {
      sniItem: bestMatch,
      similarity: Math.round(bestScore * 100) / 100,
      confidence,
      suggestionText: bestMatch.citySni
    };
  }

  return null;
}
